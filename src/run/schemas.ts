import { z } from "zod";

export const runMetadataSchema = z.object({
  version: z.literal("1.0"),
  id: z.string(),
  changeId: z.string(),
  projectPath: z.string(),
  runtime: z.enum(["local-command", "codex-readonly", "validator", "auditor", "coder-codex", "worktree-apply", "worktree-discard", "spec-test-proposer", "spec-test-generator", "spec-agent", "planner", "orchestrator", "agent-codex", "intake-scan"]),
  executionMode: z.enum(["direct", "worktree"]).optional(),
  proposalOnly: z.boolean().optional(),
  command: z.array(z.string()),
  status: z.enum(["created", "running", "completed", "failed"]),
  exitCode: z.number().nullable(),
  signal: z.string().nullable(),
  startedAt: z.string(),
  finishedAt: z.string().nullable(),
  artifacts: z.object({
    base: z.enum(["project-root", "memory-root"]).default("project-root"),
    directory: z.string(),
    context: z.string(),
    contextPacket: z.string().optional(),
    events: z.string(),
    stdout: z.string(),
    stderr: z.string(),
    prompt: z.string().optional(),
    codexEvents: z.string().optional(),
    lastMessage: z.string().optional(),
    implementation: z.string().optional(),
    worktree: z.string().optional(),
    diff: z.string().optional(),
    diffStat: z.string().optional(),
    validation: z.string().optional(),
    audit: z.string().optional(),
    auditMarkdown: z.string().optional(),
    review: z.string().optional(),
    apply: z.string().optional(),
    discard: z.string().optional(),
    specTestProposal: z.string().optional(),
    specTestProposalMarkdown: z.string().optional(),
    specProposal: z.string().optional(),
    specProposalMarkdown: z.string().optional(),
    planProposal: z.string().optional(),
    planProposalMarkdown: z.string().optional(),
    orchestrationPlan: z.string().optional(),
    orchestrationPlanMarkdown: z.string().optional(),
    intakeScan: z.string().optional(),
    intakeScanMarkdown: z.string().optional(),
  }),
  worktree: z.object({
    worktreeId: z.string(),
    branchName: z.string(),
    baseRef: z.string(),
    baseCommit: z.string(),
    checkoutPath: z.string(),
    metadataPath: z.string(),
  }).optional(),
  taskIds: z.array(z.string()).optional(),
  taskRunId: z.string().optional(),
  promptStack: z.array(z.string()).optional(),
  enabledSkills: z.array(z.object({
    id: z.string(),
    sourceHash: z.string(),
    materializedHash: z.string().nullable().optional(),
    bridge: z.string().optional(),
    version: z.string().optional(),
  })).optional(),
  agent: z.object({
    roleId: z.string(),
    source: z.enum(["bundled", "memory"]),
    sourcePath: z.string(),
    sourceHash: z.string(),
    catalogVersion: z.string(),
    catalogHash: z.string(),
    bridge: z.string().optional(),
    materializedHash: z.string().nullable().optional(),
  }).optional(),
  contextPacket: z.object({
    ref: z.string(),
    hash: z.string(),
    format: z.literal("role-context-packet@1.0"),
  }).optional(),
});
