#!/usr/bin/env node

/* global process */

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";

const ACTION_IDS = [
  "working", "standby", "coffee-drink", "peek", "off-chair", "walk-horizontal",
  "walk-vertical", "leaving", "treadmill", "toilet", "standing-talk", "seated-talk", "salute",
];
const FACILITY_ROUTES = ["coffee", "treadmill", "toilet"];
const TARGET_KEYS = ["planning", "coder", "auditor", "rework", "spec-proposer", "spec-generator", "maintenance", "evolution"];
const LAYERS = ["shadow", "desk", "screen", "actor", "chair", "effect"];

export async function compileRuntimeCalibration(inputPath, outputPath, repositoryRoot = process.cwd()) {
  const absoluteInput = resolve(repositoryRoot, inputPath);
  const absoluteOutput = resolve(repositoryRoot, outputPath);
  const source = await readFile(absoluteInput, "utf8");
  const editor = JSON.parse(source);
  validateEditorCalibration(editor);
  const runtime = toRuntimeCalibration(editor, source);
  const generated = [
    "// Generated by scripts/office-assets/compile-runtime-calibration.mjs. Do not edit.",
    'import type { OfficeRuntimeCalibrationV1 } from "./officeRuntimeCalibration.js";',
    "",
    `export const OFFICE_RUNTIME_CALIBRATION: OfficeRuntimeCalibrationV1 = ${JSON.stringify(runtime, null, 2)};`,
    "",
  ].join("\n");
  await mkdir(dirname(absoluteOutput), { recursive: true });
  await writeFile(absoluteOutput, generated, "utf8");
  return {
    input: relative(repositoryRoot, absoluteInput),
    output: relative(repositoryRoot, absoluteOutput),
    sourceSha256: runtime.sourceSha256,
    normalizedHash: runtime.normalizedHash,
  };
}

function toRuntimeCalibration(editor, source) {
  const geometry = JSON.parse(JSON.stringify(editor));
  geometry.schemaVersion = 1;
  geometry.editorSchemaVersion = 3;
  geometry.roster.seats = geometry.roster.seats.map((seat) => {
    const runtimeSeat = { ...seat };
    delete runtimeSeat.actionId;
    return runtimeSeat;
  });
  geometry.sourceSha256 = sha256(source);
  const normalized = stableStringify(geometry, new Set(["normalizedHash", "sourceSha256"]));
  geometry.normalizedHash = sha256(normalized);
  return geometry;
}

function validateEditorCalibration(value) {
  assert(value?.schemaVersion === 3, "Editor calibration schemaVersion must be 3.");
  assert(value?.world?.width === 1200 && value?.world?.height === 900, "Office world must be 1200x900.");
  assert(Array.isArray(value?.roster?.seats) && value.roster.seats.length === 9, "Office roster must contain nine seats.");
  assert(new Set(value.roster.seats.map((seat) => seat.slotId)).size === 9, "Office seat ids must be unique.");
  assertExactKeys(value.actionScales, ACTION_IDS, "action scales");
  assertExactKeys(value.actionOffsets, ACTION_IDS, "action offsets");
  for (const actionId of ACTION_IDS) {
    assertPositive(value.actionScales[actionId], `Action scale ${actionId}`);
    assertPoint(value.actionOffsets[actionId], `Action offset ${actionId}`);
  }
  assert(Object.keys(value.transitionDirections ?? {}).length >= 20, "Office transition directions are incomplete.");
  for (const [id, direction] of Object.entries(value.transitionDirections)) {
    assert([direction.fromFlipX, direction.toFlipX, direction.fromReverse, direction.toReverse].every((entry) => typeof entry === "boolean"), `Transition ${id} is invalid.`);
  }
  assertExactKeys(value.routeStageOffsets, FACILITY_ROUTES, "facility route offsets");
  assertExactKeys(value.routeStagePointOffsets, FACILITY_ROUTES, "facility route points");
  assertExactKeys(value.handoff?.targetRoutes, TARGET_KEYS, "handoff target routes");
  for (const route of FACILITY_ROUTES) validatePointTree(value.routeStageOffsets[route], `Facility route ${route}`);
  for (const route of FACILITY_ROUTES) validatePointTree(value.routeStagePointOffsets[route], `Facility points ${route}`);
  if (value.facilityRouteTargets != null) validatePointTree(value.facilityRouteTargets, "Facility target routes", true);
  validatePointTree(value.handoff.stageOffsets, "Handoff stages");
  validatePointTree(value.handoff.stagePointOffsets, "Handoff stage points");
  validatePointTree(value.handoff.stagePathPointOffsets, "Handoff path points");
  for (const key of TARGET_KEYS) validatePointTree(value.handoff.targetRoutes[key], `Handoff target ${key}`, true);
  assert(Array.isArray(value.layerOrder) && value.layerOrder.length === LAYERS.length && LAYERS.every((layer) => value.layerOrder.includes(layer)), "Office layer order is incomplete.");
  for (const kind of ["standard", "main"]) validateWorkstation(value.workstations?.[kind], `Workstation ${kind}`);
  for (const id of ["coffee", "coffeeCup", "treadmill", "toilet", "toiletPaper", "toiletTailOccluder"]) validateFacility(value.facilities?.[id], `Facility ${id}`);
}

function validateWorkstation(value, label) {
  assert(value && typeof value === "object", `${label} is missing.`);
  for (const component of ["desk", "monitor", "chair"]) {
    assertPoint(value[component], `${label} ${component}`);
    assertPositive(value[component].scaleX, `${label} ${component} scaleX`);
    assertPositive(value[component].scaleY, `${label} ${component} scaleY`);
  }
  for (const anchor of ["seat", "keyboard", "monitor", "aisleEntry"]) assertPoint(value.anchors?.[anchor], `${label} ${anchor}`);
  assertPoint(value.screen, `${label} screen`);
  assertPositive(value.screen.width, `${label} screen width`);
  assertPositive(value.screen.height, `${label} screen height`);
  validateShadow(value.shadow, `${label} shadow`);
}

function validateFacility(value, label) {
  assertPoint(value?.origin, `${label} origin`);
  assertPositive(value?.scale, `${label} scale`);
  assertPoint(value?.anchors?.aisleEntry, `${label} aisle-entry`);
  assertPoint(value?.anchors?.contact, `${label} contact`);
  if (value.shadow != null) validateShadow(value.shadow, `${label} shadow`);
}

function validateShadow(value, label) {
  assertPoint(value, label);
  assertPositive(value?.scaleX, `${label} scaleX`);
  assertPositive(value?.scaleY, `${label} scaleY`);
  assert(typeof value?.resourceId === "string" && value.resourceId.endsWith("-shadow"), `${label} resourceId is invalid.`);
  assert(value?.layer === "shadow", `${label} layer must be shadow.`);
  assert(Number.isFinite(value?.alpha) && value.alpha > 0 && value.alpha <= 1, `${label} alpha must be within (0, 1].`);
}

function validatePointTree(value, label, allowScalar = false) {
  assert(value && typeof value === "object", `${label} is missing.`);
  for (const [key, child] of Object.entries(value)) {
    if (child && typeof child === "object" && Number.isFinite(child.x) && Number.isFinite(child.y)) {
      assertPoint(child, `${label}/${key}`);
    } else if (child && typeof child === "object") {
      validatePointTree(child, `${label}/${key}`, allowScalar);
    } else if (!allowScalar || (typeof child !== "boolean" && child !== undefined)) {
      throw new Error(`${label}/${key} is invalid.`);
    }
  }
}

function assertExactKeys(value, expected, label) {
  const actual = Object.keys(value ?? {}).sort();
  const wanted = [...expected].sort();
  assert(JSON.stringify(actual) === JSON.stringify(wanted), `Office ${label} must contain exactly ${wanted.join(", ")}.`);
}

function assertPoint(value, label) {
  assert(value && Number.isFinite(value.x) && Number.isFinite(value.y), `${label} must be a finite point.`);
}

function assertPositive(value, label) {
  assert(Number.isFinite(value) && value > 0, `${label} must be positive.`);
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function stableStringify(value, excluded = new Set()) {
  if (Array.isArray(value)) return `[${value.map((entry) => stableStringify(entry, excluded)).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).filter((key) => !excluded.has(key)).sort().map((key) => `${JSON.stringify(key)}:${stableStringify(value[key], excluded)}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

if (process.argv[1]?.endsWith("compile-runtime-calibration.mjs")) {
  const input = process.argv[2];
  const output = process.argv[3] ?? "src/web/src/office/officeRuntimeCalibration.generated.ts";
  if (!input) {
    process.stderr.write("Usage: compile-runtime-calibration.mjs <editor-calibration.json> [output.ts]\n");
    process.exitCode = 1;
  } else {
    compileRuntimeCalibration(input, output).then(
      (result) => process.stdout.write(`${JSON.stringify(result, null, 2)}\n`),
      (error) => {
        process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
        process.exitCode = 1;
      },
    );
  }
}
